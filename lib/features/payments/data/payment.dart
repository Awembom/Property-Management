/// What a payment was for (`payments.kind`).
enum PaymentKind {
  /// Covers a number of months of rent.
  rent,

  /// Pays off money still owed from an earlier part payment.
  balance;

  static PaymentKind fromJson(String value) => PaymentKind.values.byName(value);
}

/// How the money was paid. Stored as text in `payments.method`.
enum PaymentMethod {
  cash('cash', 'Cash'),
  mobileMoney('mobile_money', 'Mobile money'),
  bank('bank', 'Bank transfer'),
  other('other', 'Other');

  const PaymentMethod(this.value, this.label);

  /// What the database stores.
  final String value;
  final String label;

  /// Label for a stored value (or the value itself if it's unknown).
  static String labelFor(String? value) {
    if (value == null) return 'Not recorded';
    for (final method in values) {
      if (method.value == value) return method.label;
    }
    return value;
  }
}

/// A recorded payment with its receipt (and void, if it was voided).
///
/// Payments never change after they're recorded (CLAUDE.md, rule 2). A
/// mistake is corrected by voiding the payment with a reason.
class Payment {
  const Payment({
    required this.id,
    required this.tenancyId,
    required this.propertyId,
    required this.kind,
    required this.amount,
    required this.balanceAfter,
    required this.paidOn,
    required this.receiptNumber,
    required this.issuedAt,
    required this.referenceCode,
    this.expectedAmount,
    this.months,
    this.periodStart,
    this.periodEnd,
    this.method,
    this.reference,
    this.voidReason,
    this.voidedAt,
    this.signed,
    this.response,
  });

  final String id;
  final String tenancyId;
  final String propertyId;
  final PaymentKind kind;

  /// What the tenant actually paid (smallest currency unit).
  final int amount;

  /// For rent payments: what the covered months cost (monthly rent x months).
  final int? expectedAmount;

  /// Money still owed on the tenancy right after this payment.
  /// Positive = left to pay; negative = paid in advance; 0 = fully paid.
  final int balanceAfter;

  /// Rent payments: months covered, from [periodStart] up to [periodEnd]
  /// (the new "paid until" date).
  final int? months;
  final DateTime? periodStart;
  final DateTime? periodEnd;

  /// The day the money was received.
  final DateTime paidOn;
  final String? method;

  /// Typed by staff, e.g. a mobile-money transaction ID. Shown as
  /// "Transaction ID".
  final String? reference;

  /// Generated by the database, e.g. 'PAY-7K3QX9'. A rent payment gets a new
  /// one; a payment that pays off what was left gets the SAME code as the
  /// receipt it completes, so the receipts belong together.
  final String referenceCode;

  final String receiptNumber;
  final DateTime issuedAt;

  final String? voidReason;
  final DateTime? voidedAt;

  bool get isVoided => voidedAt != null;

  /// The receipt's signed details (for its QR code), once sign-receipt ran.
  final SignedReceipt? signed;

  /// The tenant's answer (confirmed / problem reported), if they gave one.
  final ReceiptResponse? response;

  /// A copy with the signature filled in (signed after it was loaded).
  Payment withSigned(SignedReceipt value) => Payment(
        id: id,
        tenancyId: tenancyId,
        propertyId: propertyId,
        kind: kind,
        amount: amount,
        balanceAfter: balanceAfter,
        paidOn: paidOn,
        receiptNumber: receiptNumber,
        issuedAt: issuedAt,
        referenceCode: referenceCode,
        expectedAmount: expectedAmount,
        months: months,
        periodStart: periodStart,
        periodEnd: periodEnd,
        method: method,
        reference: reference,
        voidReason: voidReason,
        voidedAt: voidedAt,
        signed: value,
        response: response,
      );

  /// How much of THIS payment's months is unpaid (expected - paid), 0 if
  /// fully paid. Only for rent payments.
  int get shortfall {
    final expected = expectedAmount;
    if (expected == null) return 0;
    return expected > amount ? expected - amount : 0;
  }

  /// Columns to select, with the receipt and void embedded (one-to-one).
  static const columns = 'id, tenancy_id, property_id, kind, amount, expected_amount, '
      'balance_after, months, period_start, period_end, paid_on, method, reference, '
      'reference_code, '
      'receipt:receipts(receipt_number, issued_at, signed_payload, signature), '
      'void:payment_voids(reason, created_at), '
      '${ReceiptResponse.embed}';

  factory Payment.fromJson(Map<String, dynamic> json) {
    final receipt = json['receipt'] as Map<String, dynamic>;
    final voidRow = json['void'] as Map<String, dynamic>?;
    return Payment(
      id: json['id'] as String,
      tenancyId: json['tenancy_id'] as String,
      propertyId: json['property_id'] as String,
      kind: PaymentKind.fromJson(json['kind'] as String),
      amount: json['amount'] as int,
      expectedAmount: json['expected_amount'] as int?,
      balanceAfter: json['balance_after'] as int,
      months: json['months'] as int?,
      periodStart: parseDbDateOrNull(json['period_start'] as String?),
      periodEnd: parseDbDateOrNull(json['period_end'] as String?),
      paidOn: parseDbDate(json['paid_on'] as String),
      method: json['method'] as String?,
      reference: json['reference'] as String?,
      referenceCode: json['reference_code'] as String,
      receiptNumber: receipt['receipt_number'] as String,
      issuedAt: DateTime.parse(receipt['issued_at'] as String).toLocal(),
      voidReason: voidRow?['reason'] as String?,
      voidedAt: voidRow == null ? null : DateTime.parse(voidRow['created_at'] as String).toLocal(),
      signed: receipt['signature'] == null
          ? null
          : SignedReceipt(
              payload: receipt['signed_payload'] as String,
              signature: receipt['signature'] as String,
            ),
      response: ReceiptResponse.fromEmbed(json['response']),
    );
  }
}

/// What record_payment() returns. Contains no money, so caretakers get it too.
class RecordedPayment {
  const RecordedPayment({
    required this.paymentId,
    required this.receiptNumber,
    required this.paidUntil,
  });

  final String paymentId;
  final String receiptNumber;
  final DateTime paidUntil;
}
